"""Regenerate basepoint_table.in using affine Edwards25519 arithmetic."""

from pathlib import Path

P = 2**255 - 19
D = -121665 * pow(121666, -1, P) % P
# RFC 8032 base point with even x and y = 4/5.
BX = 15112221349535400772501151409588531511454012693041857206046113283949847762202
BY = 4 * pow(5, -1, P) % P
MAX_DIGIT = 136


def add_basepoint(x, y):
    product = D * x * BX * y * BY % P
    return ((x * BY + y * BX) * pow(1 + product, -1, P) % P,
            (y * BY + x * BX) * pow(1 - product, -1, P) % P)


def limbs(value):
    value %= P
    return [(value >> (51 * i)) & (2**51 - 1) for i in range(5)]


def generate():
    multiples = [(0, 1)]
    for _ in range(MAX_DIGIT):
        multiples.append(add_basepoint(*multiples[-1]))

    lines = ["// Generated by generate_basepoint_table.py.", "["]
    for digit in range(-MAX_DIGIT, MAX_DIGIT + 1):
        x, y = multiples[abs(digit)]
        if digit < 0:
            x = -x
        lines.append(f"    entry( // [{digit}]B")
        for value in (y - x, y + x, 2 * D * x * y):
            lines.append(f"        {limbs(value)},")
        lines.append("    ),")
    return "\n".join([*lines, "]", ""])


if __name__ == "__main__":
    Path(__file__).with_name("basepoint_table.in").write_text(generate())
